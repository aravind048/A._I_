# Define maximum sequence length
MAX_LEN = 512 # BERT's maximum input length

# Tokenize and create input sequences
input_ids = []
attention_masks = []
token_type_ids = []

for index, row in df.iterrows():
    encoded_dict = tokenizer.encode_plus(
        row['cleaned_resume'],      # Resume text
        row['cleaned_job_description'], # Job description text
        add_special_tokens = True,  # Add '[CLS]' and '[SEP]'
        max_length = MAX_LEN,       # Pad or truncate
        padding = 'max_length',   # Pad to max length
        truncation=True,         # truncate long sequences
        return_attention_mask = True, # Construct attention mask
        return_token_type_ids = True, # Construct token type IDs
        return_tensors = 'pt',      # Return pytorch tensors
    )

    input_ids.append(encoded_dict['input_ids'])
    attention_masks.append(encoded_dict['attention_mask'])
    token_type_ids.append(encoded_dict['token_type_ids'])

# Concatenate the tensors
input_ids = torch.cat(input_ids, dim=0)
